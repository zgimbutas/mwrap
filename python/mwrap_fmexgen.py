def _print_handle_inout(fp, f, i8_mode):
    """For inout arrays: create output mxArray, copy input data, set pointer."""
    has_inout = any(v.iospec == 'b' and is_array(v.tinfo) for v in f.args)
    if not has_inout:
        return

    _wc(fp, "handle inout arrays: create output, copy input", 4)

    for v in f.args:
        if v.iospec != 'b' or not is_array(v.tinfo):
            continue

        il = v.input_label
        ol = v.output_label
        idx_in = il + 1
        idx_out = ol + 1
        ft, is_cplx, is_native = _fort_type(v.basetype, i8_mode)
        da = v.qual.args if v.qual else []

        if _is_scalar_array(v) and _dim_product(v) == 1:
            # Scalar inout: already handled in unpack_inputs
            # Will marshal after the call
            continue

        # Get dimensions
        if da:
            if len(da) == 1:
                dim_m = _dim_label(da[0])
                dim_n = "1_c_size_t"
            elif len(da) == 2:
                dim_m = _dim_label(da[0])
                dim_n = _dim_label(da[1])
            else:
                dim_m = _alloc_size_expr(da)
                dim_n = "1_c_size_t"
            sz = _alloc_size_expr(da)
        else:
            # No explicit dims: use input array size
            _w(fp, f"inout{il}_m_ = mxGetM(prhs({idx_in}))", 4)
            _w(fp, f"inout{il}_n_ = mxGetN(prhs({idx_in}))", 4)
            dim_m = f"inout{il}_m_"
            dim_n = f"inout{il}_n_"
            sz = f"inout{il}_m_ * inout{il}_n_"

        # Create output mxArray
        cflag = "1" if is_cplx else "0"
        _w(fp, f"plhs({idx_out}) = mxCreateDoubleMatrix({dim_m}, {dim_n}, {cflag})", 4)

        if is_native:
            # Copy input data to output, point in{il}_ at output
            _w(fp, f"call c_f_pointer(mxGetPr(prhs({idx_in})), inout{il}_src_, [{sz}])", 4)
            _w(fp, f"call c_f_pointer(mxGetPr(plhs({idx_out})), in{il}_, [{sz}])", 4)
            _w(fp, f"in{il}_(1:{sz}) = inout{il}_src_(1:{sz})", 4)
        else:
            # Need to convert from double, write back after call
            _w(fp, f"call c_f_pointer(mxGetPr(prhs({idx_in})), inout{il}_src_dbl_, [{sz}])", 4)
            _w(fp, f"allocate(in{il}_({sz}))", 4)
            _w(fp, f"do mwf_i_ = 1, {sz}", 4)
            _w(fp, f"  in{il}_(mwf_i_) = int(inout{il}_src_dbl_(mwf_i_), {_int_kind(i8_mode)})", 6)
            _w(fp, f"end do", 4)

    fp.write("\n")


