def _print_make_call(fp, f, i8_mode):
    _wc(fp, "make the call", 4)

    # Build argument list
    call_args = []
    for v in f.args:
        if v.tinfo == VT.const:
            call_args.append(v.name)
        elif is_array(v.tinfo):
            n = vname(v)
            if _is_scalar_array(v) and _dim_product(v) == 1:
                # Scalar by ref: pass local variable (Fortran passes by ref)
                call_args.append(n)
            else:
                # Array: pass the pointer/allocatable
                call_args.append(n)
        elif v.tinfo in (VT.p_scalar, VT.p_cscalar, VT.p_zscalar):
            call_args.append(vname(v))
        elif v.tinfo == VT.string:
            call_args.append(vname(v))
        else:
            call_args.append(vname(v))

    args_str = ", &\n        ".join(call_args) if len(call_args) > 4 else ", ".join(call_args)

    if f.ret and f.ret[0].tinfo == VT.scalar:
        _w(fp, f"out0_ = {f.funcv}({args_str})", 4)
    else:
        _w(fp, f"call {f.funcv}({args_str})", 4)

    fp.write("\n")


