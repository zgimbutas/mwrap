# ===================================================================
# Type mapping: mwrap base types -> Fortran iso_c_binding types
# ===================================================================

# Maps mwrap base type to (fortran_type, is_complex, is_native_double)
# is_native_double: True if mxArray data is double and can be used directly
FMEX_TYPE_MAP = {
    "double":   ("real(c_double)",             False, True),
    "float":    ("real(c_float)",              False, False),
    "int":      ("integer(c_int)",             False, False),
    "int32_t":  ("integer(c_int32_t)",         False, False),
    "int64_t":  ("integer(c_int64_t)",         False, False),
    "dcomplex": ("complex(c_double_complex)",  True,  True),
    "fcomplex": ("complex(c_float_complex)",   True,  False),
}

# With -i8, integer types are promoted
FMEX_TYPE_MAP_I8 = {
    "double":   ("real(c_double)",             False, True),
    "float":    ("real(c_float)",              False, False),
    "int":      ("integer(8)",                 False, False),
    "int32_t":  ("integer(8)",                 False, False),
    "int64_t":  ("integer(8)",                 False, False),
    "dcomplex": ("complex(c_double_complex)",  True,  True),
    "fcomplex": ("complex(c_float_complex)",   True,  False),
}

_DEFAULT_TYPE = ("real(c_double)", False, True)


def _fort_type(basetype, i8_mode):
    """Get (fortran_type, is_complex, is_native) for a base type."""
    m = FMEX_TYPE_MAP_I8 if i8_mode else FMEX_TYPE_MAP
    return m.get(basetype, _DEFAULT_TYPE)


def _int_kind(i8_mode):
    """Fortran integer kind for user-facing integers."""
    return "8" if i8_mode else "c_int"


# ===================================================================
# Variable naming
# ===================================================================

def vname(v):
    if v.iospec == 'o':
        return f"out{v.output_label}_"
    return f"in{v.input_label}_"


# ===================================================================
# Classify variables for code generation
# ===================================================================

def _is_scalar_array(v):
    """True if v is an array with all-literal dimensions (e.g. int[1])."""
    if not (v.qual and v.qual.args):
        return False
    return all(e.value.isdigit() for e in v.qual.args)


def _dim_product(v):
    """Product of literal dimension values, or None if not all-literal."""
    if not (v.qual and v.qual.args):
        return None
    try:
        p = 1
        for e in v.qual.args:
            p *= int(e.value)
        return p
    except ValueError:
        return None


def _needs_conversion(basetype):
    """True if mxArray data (double) must be converted for this type."""
    return basetype not in ("double", "dcomplex")


# ===================================================================
# Helper: dimension expression in Fortran
# ===================================================================

def _alloc_size_expr(args):
    """Fortran expression for product of dim args."""
    if not args:
        return "1"
    return " * ".join(f"dim{e.input_label}_" for e in args)


def _dim_label(e):
    return f"dim{e.input_label}_"


# ===================================================================
# Write helpers (free-form, no column limit concern)
# ===================================================================

def _w(fp, text, indent=2):
    """Write an indented line."""
    fp.write(" " * indent + text + "\n")


def _wc(fp, text, indent=2):
    """Write a comment line."""
    fp.write(" " * indent + "! " + text + "\n")


