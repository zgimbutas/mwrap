def _print_unpack_dims(fp, f, i8_mode):
    has_dims = False
    for v in (f.ret or []) + f.args:
        if v.qual and v.qual.args:
            has_dims = True
            break
    if not has_dims:
        return

    _wc(fp, "unpack dimensions", 4)
    for v in (f.ret or []) + f.args:
        if v.qual and v.qual.args:
            for e in v.qual.args:
                idx = e.input_label + 1
                _w(fp, f"{_dim_label(e)} = int(mxGetScalar(prhs({idx})), c_size_t)", 4)
    fp.write("\n")


