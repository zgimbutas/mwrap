def _print_alloc_outputs(fp, f, i8_mode):
    """Allocate output-only arrays."""
    has_out = False
    for v in (f.ret or []) + f.args:
        if v.iospec == 'o' and is_array(v.tinfo):
            has_out = True
    if not has_out:
        return

    _wc(fp, "allocate output arrays", 4)
    for v in (f.ret or []) + f.args:
        if v.iospec != 'o' or not is_array(v.tinfo):
            continue
        ol = v.output_label
        idx = ol + 1
        ft, is_cplx, is_native = _fort_type(v.basetype, i8_mode)
        da = v.qual.args if v.qual else []

        if len(da) == 1:
            dim_m = _dim_label(da[0])
            dim_n = "1_c_size_t"
        elif len(da) == 2:
            dim_m = _dim_label(da[0])
            dim_n = _dim_label(da[1])
        else:
            dim_m = _alloc_size_expr(da)
            dim_n = "1_c_size_t"
        sz = _alloc_size_expr(da)

        cflag = "1" if is_cplx else "0"
        _w(fp, f"plhs({idx}) = mxCreateDoubleMatrix({dim_m}, {dim_n}, {cflag})", 4)

        if is_native:
            _w(fp, f"call c_f_pointer(mxGetPr(plhs({idx})), out{ol}_, [{sz}])", 4)
        else:
            _w(fp, f"allocate(out{ol}_({sz}))", 4)

    fp.write("\n")


