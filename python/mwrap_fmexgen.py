def _print_marshal_results(fp, f, i8_mode):
    """Marshal scalar outputs and inout scalars back to plhs."""
    has_marshal = False

    # Return value
    if f.ret and f.ret[0].tinfo == VT.scalar:
        has_marshal = True
    # Inout scalar arrays (int[1])
    for v in f.args:
        if v.iospec == 'b' and is_array(v.tinfo) and _is_scalar_array(v) and _dim_product(v) == 1:
            has_marshal = True
    # Output scalar args
    for v in (f.ret or []) + f.args:
        if v.iospec == 'o' and v.tinfo in (VT.scalar, VT.p_scalar):
            has_marshal = True
    # Inout non-native arrays (need to convert back)
    for v in f.args:
        if v.iospec == 'b' and is_array(v.tinfo) and _needs_conversion(v.basetype):
            if not (_is_scalar_array(v) and _dim_product(v) == 1):
                has_marshal = True

    if not has_marshal:
        return

    _wc(fp, "marshal outputs", 4)

    # Return value (scalar)
    if f.ret:
        v = f.ret[0]
        if v.tinfo == VT.scalar:
            _w(fp, f"plhs(1) = mxCreateDoubleMatrix(1_c_size_t, 1_c_size_t, 0)", 4)
            _w(fp, f"call c_f_pointer(mxGetPr(plhs(1)), ret_dbl_, [1])", 4)
            _w(fp, f"ret_dbl_(1) = dble(out0_)", 4)

    # Inout scalar arrays (e.g. inout int[1] ier)
    for v in f.args:
        if v.iospec != 'b' or not is_array(v.tinfo):
            continue
        if not (_is_scalar_array(v) and _dim_product(v) == 1):
            continue
        il = v.input_label
        ol = v.output_label
        idx = ol + 1
        _w(fp, f"plhs({idx}) = mxCreateDoubleMatrix(1_c_size_t, 1_c_size_t, 0)", 4)
        _w(fp, f"call c_f_pointer(mxGetPr(plhs({idx})), out{ol}_dbl_, [1])", 4)
        _w(fp, f"out{ol}_dbl_(1) = dble(in{il}_)", 4)

    # Output-only scalars
    for v in (f.ret or []) + f.args:
        if v.iospec != 'o':
            continue
        if v.tinfo in (VT.scalar, VT.p_scalar):
            ol = v.output_label
            idx = ol + 1
            _w(fp, f"plhs({idx}) = mxCreateDoubleMatrix(1_c_size_t, 1_c_size_t, 0)", 4)
            _w(fp, f"call c_f_pointer(mxGetPr(plhs({idx})), out{ol}_dbl_, [1])", 4)
            _w(fp, f"out{ol}_dbl_(1) = dble(out{ol}_)", 4)

    # Inout non-native arrays: convert back to double and write to output
    for v in f.args:
        if v.iospec != 'b' or not is_array(v.tinfo):
            continue
        if _is_scalar_array(v) and _dim_product(v) == 1:
            continue
        if not _needs_conversion(v.basetype):
            continue
        il = v.input_label
        ol = v.output_label
        idx = ol + 1
        da = v.qual.args if v.qual else []
        if da:
            sz = _alloc_size_expr(da)
        else:
            sz = f"inout{il}_m_ * inout{il}_n_"
        _w(fp, f"call c_f_pointer(mxGetPr(plhs({idx})), out{ol}_dbl_, [{sz}])", 4)
        _w(fp, f"do mwf_i_ = 1, {sz}", 4)
        _w(fp, f"  out{ol}_dbl_(mwf_i_) = dble(in{il}_(mwf_i_))", 6)
        _w(fp, f"end do", 4)

    fp.write("\n")


# ===================================================================
# Per-stub: cleanup allocatables
# ===================================================================

def _print_cleanup(fp, f, i8_mode):
    """Deallocate temporary arrays."""
    has_cleanup = False
    for v in f.args:
        if is_array(v.tinfo) and _needs_conversion(v.basetype):
            if not (_is_scalar_array(v) and _dim_product(v) == 1):
                has_cleanup = True

    if not has_cleanup:
        return

    _wc(fp, "cleanup", 4)
    for v in f.args:
        if not is_array(v.tinfo) or not _needs_conversion(v.basetype):
            continue
        if _is_scalar_array(v) and _dim_product(v) == 1:
            continue
        n = vname(v)
        _w(fp, f"if (allocated({n})) deallocate({n})", 4)

    fp.write("\n")


# ===================================================================
# Print a single stub
# ===================================================================

def _print_stub_comment(fp, f):
    fp.write(f"\n! ---- {f.fname}: {f.line} ----\n")
    desc = print_func(f).rstrip('\n')
    fp.write(f"! {desc}\n")
    if f.same:
        fsame = f.same[0]
        fp.write(f"! Also at {fsame.fname}: {fsame.line}\n")


def _print_stub(fp, ctx, f, i8_mode):
    ids = id_string(ctx, f)
    _print_stub_comment(fp, f)

    fp.write(f"\nsubroutine mwfStub{f.id}(nlhs, plhs, nrhs, prhs)\n")
    _w(fp, "use iso_c_binding")
    _w(fp, "use mwrap_mex")
    _w(fp, "implicit none")
    _w(fp, "integer(c_int), intent(in) :: nlhs, nrhs")
    _w(fp, "type(c_ptr), intent(inout) :: plhs(*)")
    _w(fp, "type(c_ptr), intent(in) :: prhs(*)")
    fp.write("\n")

    _print_declarations(fp, f, i8_mode)
    _print_unpack_dims(fp, f, i8_mode)
    _print_unpack_inputs(fp, f, i8_mode)
    _print_handle_inout(fp, f, i8_mode)
    _print_alloc_outputs(fp, f, i8_mode)
    _print_make_call(fp, f, i8_mode)
    _print_marshal_results(fp, f, i8_mode)
    _print_cleanup(fp, f, i8_mode)

    fp.write("end subroutine mwfStub{}\n".format(f.id))


# ===================================================================
# Print gateway
# ===================================================================

def _print_gateway(fp, funcs, mexfunc, i8_mode):
    fp.write("\n")
    fp.write("! " + "=" * 65 + "\n")
    fp.write("! Gateway: mexFunction\n")
    fp.write("! " + "=" * 65 + "\n")

    fp.write(f'\nsubroutine mexFunction(nlhs, plhs, nrhs, prhs) &\n')
    fp.write(f'    bind(C, name="mexFunction")\n')
    _w(fp, "use iso_c_binding")
    _w(fp, "use mwrap_mex")
    _w(fp, "implicit none")
    _w(fp, "integer(c_int), value :: nlhs, nrhs")
    _w(fp, "type(c_ptr) :: plhs(*)")
    _w(fp, "type(c_ptr) :: prhs(*)")
    _w(fp, "integer(c_int) :: stub_id_")
    fp.write("\n")
    _w(fp, "stub_id_ = int(mxGetScalar(prhs(1)), c_int)")
    fp.write("\n")

    # Build dispatch
    id_to_primary = {}
    for f in funcs:
        id_to_primary[f.id] = f.id
        for fsame in f.same:
            id_to_primary[fsame.id] = f.id

    all_ids = sorted(id_to_primary.keys())

    if not all_ids:
        _w(fp, "call mexErrMsgTxt('No functions registered' // c_null_char)")
    else:
        first = True
        for sid in all_ids:
            pid = id_to_primary[sid]
            if first:
                _w(fp, f"if (stub_id_ == {sid}) then")
                first = False
            else:
                _w(fp, f"else if (stub_id_ == {sid}) then")
            _w(fp, f"  call mwfStub{pid}(nlhs, plhs, nrhs - 1, prhs(2))", 2)
        _w(fp, "else")
        _w(fp, "  call mexErrMsgTxt('Unknown function ID' // c_null_char)")
        _w(fp, "end if")

    fp.write("\nend subroutine mexFunction\n")


# ===================================================================
# Top-level: print_fmex_file
# ===================================================================

def print_fmex_file(fp, ctx, funcs, mexfunc, i8_mode=False):
    """Write all stubs and the gateway."""
    # Validate: all functions must be Fortran in -fmex mode
    for f in funcs:
        if not f.fort:
            sys.stderr.write(
                f"Error ({f.fname}:{f.line}): "
                f"Function '{f.funcv}' is not declared as FORTRAN. "
                f"All functions must use FORTRAN in -fmex mode.\n")
            return

    # Print stubs
    for f in funcs:
        _print_stub(fp, ctx, f, i8_mode)

    # Print gateway
    _print_gateway(fp, funcs, mexfunc, i8_mode)
