# Per-stub: unpack inputs
# ===================================================================

def _print_unpack_inputs(fp, f, i8_mode):
    has_inputs = any(v.iospec != 'o' and v.tinfo != VT.const for v in f.args)
    if not has_inputs:
        return

    _wc(fp, "unpack inputs", 4)
    fort_int = f"integer({_int_kind(i8_mode)})"

    for v in f.args:
        if v.iospec == 'o' or v.tinfo == VT.const:
            continue

        il = v.input_label
        idx = il + 1
        ft, is_cplx, is_native = _fort_type(v.basetype, i8_mode)

        if is_array(v.tinfo):
            da = v.qual.args if v.qual else []

            if _is_scalar_array(v) and _dim_product(v) == 1:
                # Scalar-by-reference: extract via mxGetScalar
                bt = v.basetype
                if bt in ("int", "int32_t"):
                    kind = _int_kind(i8_mode)
                    _w(fp, f"in{il}_ = int(mxGetScalar(prhs({idx})), {kind})", 4)
                elif bt == "int64_t":
                    _w(fp, f"in{il}_ = int(mxGetScalar(prhs({idx})), c_int64_t)", 4)
                else:
                    _w(fp, f"in{il}_ = mxGetScalar(prhs({idx}))", 4)
            elif is_native:
                # Native type: use c_f_pointer
                if da:
                    sz = _alloc_size_expr(da)
                else:
                    sz = f"int(mxGetM(prhs({idx})) * mxGetN(prhs({idx})), c_size_t)"
                _w(fp, f"call c_f_pointer(mxGetPr(prhs({idx})), in{il}_, [{sz}])", 4)
            else:
                # Needs conversion from double
                if da:
                    sz = _alloc_size_expr(da)
                else:
                    sz = f"int(mxGetM(prhs({idx})) * mxGetN(prhs({idx})), c_size_t)"
                _w(fp, f"call c_f_pointer(mxGetPr(prhs({idx})), in{il}_dbl_, [{sz}])", 4)
                _w(fp, f"allocate(in{il}_({sz}))", 4)
                _w(fp, f"do mwf_i_ = 1, {sz}", 4)
                _w(fp, f"  in{il}_(mwf_i_) = int(in{il}_dbl_(mwf_i_), {_int_kind(i8_mode)})", 6)
                _w(fp, f"end do", 4)

        elif v.tinfo in (VT.p_scalar, VT.p_cscalar, VT.p_zscalar):
            bt = v.basetype
            if bt in ("int", "int32_t"):
                kind = _int_kind(i8_mode)
                _w(fp, f"in{il}_ = int(mxGetScalar(prhs({idx})), {kind})", 4)
            elif bt == "int64_t":
                _w(fp, f"in{il}_ = int(mxGetScalar(prhs({idx})), c_int64_t)", 4)
            elif bt in ("double", "float"):
                _w(fp, f"in{il}_ = mxGetScalar(prhs({idx}))", 4)
            else:
                _w(fp, f"in{il}_ = mxGetScalar(prhs({idx}))", 4)

        elif v.tinfo == VT.string:
            _w(fp, f"in{il}_stat_ = mxGetString(prhs({idx}), in{il}_, 1024_c_int)", 4)

    fp.write("\n")


