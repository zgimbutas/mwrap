def _print_declarations(fp, f, i8_mode):
    """Declare all local variables for a stub."""
    fort_int = f"integer({_int_kind(i8_mode)})"

    # Dimension variables
    for v in (f.ret or []) + f.args:
        if v.qual and v.qual.args:
            for e in v.qual.args:
                _w(fp, f"integer(c_size_t) :: {_dim_label(e)}", 4)

    # Input variables
    for v in f.args:
        if v.iospec == 'o' or v.tinfo == VT.const:
            continue

        il = v.input_label
        ft, is_cplx, is_native = _fort_type(v.basetype, i8_mode)

        if is_array(v.tinfo):
            if _is_scalar_array(v) and _dim_product(v) == 1:
                # Scalar-by-reference: local variable, passed by ref
                _w(fp, f"{ft} :: in{il}_", 4)
            elif is_native:
                # Native type: use c_f_pointer directly
                _w(fp, f"{ft}, pointer :: in{il}_(:)", 4)
            else:
                # Needs conversion from double
                _w(fp, f"{ft}, allocatable :: in{il}_(:)", 4)
                _w(fp, f"real(c_double), pointer :: in{il}_dbl_(:)", 4)
        elif v.tinfo in (VT.p_scalar, VT.p_cscalar, VT.p_zscalar):
            _w(fp, f"{ft} :: in{il}_", 4)
        elif v.tinfo == VT.string:
            _w(fp, f"character(len=1024) :: in{il}_", 4)
            _w(fp, f"integer(c_int) :: in{il}_stat_", 4)

    # Output variables
    for v in (f.ret or []) + f.args:
        if v.iospec != 'o':
            continue
        ol = v.output_label
        ft, is_cplx, is_native = _fort_type(v.basetype, i8_mode)

        if is_array(v.tinfo):
            if is_native:
                _w(fp, f"{ft}, pointer :: out{ol}_(:)", 4)
            else:
                _w(fp, f"{ft}, allocatable :: out{ol}_(:)", 4)
                _w(fp, f"real(c_double), pointer :: out{ol}_dbl_(:)", 4)
        elif v.tinfo in (VT.scalar, VT.p_scalar):
            _w(fp, f"{ft} :: out{ol}_", 4)
            _w(fp, f"real(c_double), pointer :: out{ol}_dbl_(:)", 4)
        elif v.tinfo in (VT.p_cscalar, VT.p_zscalar):
            _w(fp, f"{ft} :: out{ol}_", 4)

    # Inout arrays: need pointers for input copy and marshal temps
    for v in f.args:
        if v.iospec != 'b':
            continue
        il = v.input_label
        ol = v.output_label
        ft, is_cplx, is_native = _fort_type(v.basetype, i8_mode)

        if is_array(v.tinfo):
            if _is_scalar_array(v) and _dim_product(v) == 1:
                # Scalar inout: need a double pointer for marshalling output
                _w(fp, f"real(c_double), pointer :: out{ol}_dbl_(:)", 4)
            elif is_native:
                # Need a pointer for output + pointer for input copy
                _w(fp, f"{ft}, pointer :: inout{il}_src_(:)", 4)
            else:
                _w(fp, f"real(c_double), pointer :: inout{il}_src_dbl_(:)", 4)
            # Dimension vars for inout arrays without explicit dims
            if not (v.qual and v.qual.args):
                _w(fp, f"integer(c_size_t) :: inout{il}_m_, inout{il}_n_", 4)

    # Return value
    if f.ret:
        v = f.ret[0]
        if v.tinfo == VT.scalar:
            ft, _, _ = _fort_type(v.basetype, i8_mode)
            _w(fp, f"{ft} :: out0_", 4)
            _w(fp, f"real(c_double), pointer :: ret_dbl_(:)", 4)

    # Temp integer for loop index (if needed for conversion)
    needs_loop = False
    for v in (f.ret or []) + f.args:
        if is_array(v.tinfo) and _needs_conversion(v.basetype):
            if not (_is_scalar_array(v) and _dim_product(v) == 1):
                needs_loop = True
    if needs_loop:
        _w(fp, f"integer(c_size_t) :: mwf_i_", 4)

    fp.write("\n")


